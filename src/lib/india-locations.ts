/**
 * Find the state+city for a given city name (case-insensitive).
 * Returns null if the city is not in the dataset.
 */
export function findIndiaCity(cityName: string): { state: string; city: IndiaCity } | null {
  const q = cityName.trim().toLowerCase();
  for (const s of INDIA_STATES) {
    const c = s.cities.find((x) => x.name.toLowerCase() === q);
    if (c) return { state: s.state, city: c };
  }
  return null;
}
